import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const source = join(root, 'sources/headplane');
const lockPath = join(root, 'sources.lock.json');
const lock = JSON.parse(await readFile(lockPath, 'utf8'));
const git = (...args) => execFileSync('git', ['-C', source, ...args], { maxBuffer: 20 * 1024 * 1024 });
if (git('rev-parse', 'HEAD').toString().trim() !== lock.headplane.commit) throw new Error('Source HEAD differs from locked baseline');
const added = git('ls-files', '--others', '--exclude-standard', '-z').toString().split('\0').filter(Boolean);
if (added.length) git('add', '--intent-to-add', '--', ...added);
git('diff', '--check');
const patch = git('diff', '--binary', '--no-ext-diff', 'HEAD');
await mkdir(join(root, 'patches'), { recursive: true });
await writeFile(join(root, 'patches/headplane-560.patch'), patch);
lock.headplane.patchSha256 = createHash('sha256').update(patch).digest('hex');
await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
console.log(`Exported Headplane patch (${patch.length} bytes); SHA256 recorded in sources.lock.json`);
