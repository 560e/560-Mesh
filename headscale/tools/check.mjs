import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const deployment = fileURLToPath(new URL('../../head-docker/', import.meta.url));
const require = createRequire(join(root, 'sources/headplane/package.json'));
const { parse } = require('yaml');
const text = (path) => readFile(join(path === 'docker-compose.yml' || path.startsWith('config/') ? deployment : root, path), 'utf8');
const lock = JSON.parse(await text('sources.lock.json'));
const sha = (data) => createHash('sha256').update(data).digest('hex');
assert.equal(sha(await readFile(join(root, 'patches/headplane-560.patch'))), lock.headplane.patchSha256);
assert.equal(sha(await readFile(join(deployment, 'config/headscale/config.official-v0.29.6.yaml'))), lock.headscale.configSha256);
const compose = parse(await text('docker-compose.yml'));
assert.deepEqual(Object.keys(compose.services), ['platform']);
assert.deepEqual(compose.services.platform.ports, ['127.0.0.1:56005:3000', '127.0.0.1:56201:8080']);
assert.equal(compose.services.platform.read_only, true);
assert.equal(compose.services.platform.user, '65532:65532');
assert.equal(compose.services.platform.volumes.some((value) => value.includes('docker.sock')), false);
const hs = parse((await text('config/headscale/config.example.yaml')).replaceAll('__PUBLIC_URL__', '"https://hs.example.com"').replaceAll('__BASE_DOMAIN__', '"tailnet.example.com"').replaceAll('__MAGIC_DNS__', 'true'));
assert.equal(hs.policy.mode, 'database');
assert.equal(hs.listen_addr, '0.0.0.0:8080');
assert.equal(hs.derp.server.enabled, false);
for (const name of await readdir(join(deployment, 'platform'))) if (name.endsWith('.mjs')) execFileSync(process.execPath, ['--check', join(deployment, 'platform', name)]);
console.log('PASS: locked artifacts, Compose/YAML contracts, loopback ports, non-root/read-only settings, platform syntax. Docker daemon checks were not performed.');
